@dataclass
class AppContext:
    db: Database
    config: AppConfig
    settings: RuntimeSettings
    now: datetime

    @property
    def tz(self) -> str:
        return self.settings.timezone

    def local(self, dt: datetime | None, fmt: str = "%Y-%m-%d %H:%M:%S") -> str:
        return format_local(dt, self.tz, fmt)


def goto(page: str, machine_id: str | None = None) -> None:
    """Button callback: navigate to a page (and optionally preselect a machine)."""
    st.session_state["nav_page"] = page
    if machine_id:
        st.session_state["machine_detail_select"] = machine_id


def header(title: str, subtitle: str | None = None) -> None:
    st.title(title)
    if subtitle:
        st.caption(subtitle)


def simulated_banner(visible: bool) -> None:
    if visible:
        st.markdown(
            '<div class="tmi-sim"><b>SIMULATED / SYNTHETIC DATA</b> — the machines, readings and '
            "states shown here are generated by the built-in simulator. They are not measurements "
            "from real textile machinery.</div>",
            unsafe_allow_html=True,
        )


def show_table(df: pd.DataFrame, key: str | None = None) -> None:
    """Render a dataframe full-width across Streamlit versions."""
    try:
        st.dataframe(df, hide_index=True, width="stretch", key=key)
    except Exception:  # older Streamlit without width="stretch"
        try:
            st.dataframe(df, hide_index=True, use_container_width=True)
        except Exception:
            st.dataframe(df)


def empty_state(message: str) -> None:
    st.info(message)


def show_error(exc: Exception) -> None:
    """Present an expected application error clearly; log unexpected ones."""
    if isinstance(exc, ValidationFailed):
        for issue in exc.issues:
            st.error(f"{issue.field.replace('_', ' ').capitalize()}: {issue.message}")
    elif isinstance(exc, AppError):
        st.error(str(exc))
    else:
        logger.exception("Unexpected error")
        st.error("An unexpected error occurred. Nothing was changed. Details are in the log file.")


def flash(message: str) -> None:
    """Queue a success message to be shown after the next rerun."""
    st.session_state.setdefault("_flash", []).append(message)


def show_flash() -> None:
    for message in st.session_state.pop("_flash", []):
        st.success(message)


def guarded(action: Callable[[], None], rerun: bool = True) -> bool:
    """Run ``action``; show errors; on success optionally rerun so the page reflects the change."""
    try:
        action()
    except Exception as exc:  # noqa: BLE001 - presented to the user, logged if unexpected
        show_error(exc)
        return False
    if rerun:
        st.rerun()
    return True


PRESETS = {
    "Last 1 hour": timedelta(hours=1),
    "Last 6 hours": timedelta(hours=6),
    "Last 24 hours": timedelta(hours=24),
    "Last 7 days": timedelta(days=7),
}


def period_selector(ctx: AppContext, key: str, default: str = "Last 6 hours") -> Window | None:
    """Preset or custom reporting window in the reporting time zone. ``None`` on invalid input."""
    options = [*PRESETS, "Custom range"]
    choice = st.selectbox("Period", options, index=options.index(default), key=f"{key}_period")
    if choice != "Custom range":
        return Window(ctx.now - PRESETS[choice], ctx.now)
    zone = get_zone(ctx.tz)
    local_now = ctx.now.astimezone(zone).replace(tzinfo=None)
    c1, c2, c3, c4 = st.columns(4)
    d1 = c1.date_input("From date", (local_now - timedelta(days=1)).date(), key=f"{key}_d1")
    t1 = c2.time_input("From time", time(0, 0), key=f"{key}_t1")
    d2 = c3.date_input("To date", local_now.date(), key=f"{key}_d2")
    t2 = c4.time_input("To time", local_now.time().replace(second=0, microsecond=0), key=f"{key}_t2")
    try:
        window = local_range_to_window(datetime.combine(d1, t1), datetime.combine(d2, t2), ctx.tz)
    except ValueError as exc:
        st.error(f"Invalid period: {exc}")
        return None
    st.caption(f"Times are interpreted in {ctx.tz}. The end of the period is exclusive.")
    return window


def window_caption(ctx: AppContext, window: Window) -> None:
    st.caption(f"Period: {ctx.local(window.start)} → {ctx.local(window.end)} ({ctx.tz}); start inclusive, end exclusive.")


def now_utc() -> datetime:
    return utc_now()
